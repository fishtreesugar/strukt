defmodule Strukt.EmbedLifecycleTest do
  use ExUnit.Case, async: true
  import ExUnit.CaptureIO
  alias Strukt.Test.Lifecycle.{Child, Parent, RequiredLists}

  defp compile(name, body) do
    Code.compile_string("defmodule #{name} do\nuse Strukt\n#{body}\nend")
  end

  describe "nested autogenerated fields" do
    test "new records in every embed kind get timestamps" do
      assert {:ok, parent} =
               Parent.new(
                 child: %{name: "child"},
                 kids: [%{name: "kid"}],
                 poly: %{__type__: "child", name: "poly"},
                 polys: [%{__type__: "child", name: "polys"}]
               )

      for child <- [parent.child, hd(parent.kids), parent.poly, hd(parent.polys)] do
        assert %NaiveDateTime{} = child.inserted_at
        assert %NaiveDateTime{} = child.updated_at
        assert is_binary(child.uuid)
      end
    end

    test "appended entries are generated while existing entries keep their values" do
      {:ok, parent} = Parent.new(kids: [%{name: "old"}])
      [old] = parent.kids
      old = %{old | inserted_at: ~N[2000-01-01 00:00:00]}
      parent = %{parent | kids: [old]}

      cs = Parent.change(parent, kids: [%{uuid: old.uuid, name: "renamed"}, %{name: "new"}])
      assert {:ok, %{kids: [renamed, new]}} = Parent.from_changeset(cs)
      assert renamed.inserted_at == ~N[2000-01-01 00:00:00]
      assert %NaiveDateTime{} = new.inserted_at
      assert new.inserted_at != old.inserted_at
    end

    test "the generated marker does not reach plain Ecto children" do
      assert {:ok, %{plain: %{name: "plain"}}} = Parent.new(plain: %{name: "plain"})
    end
  end

  describe "required lists" do
    test "missing and empty lists are rejected without Ecto warnings" do
      stderr =
        capture_io(:stderr, fn ->
          for params <- [%{}, %{items: [], variants: []}] do
            assert {:error, cs} = RequiredLists.new(params)
            assert cs.errors[:items] == {"can't be blank", [validation: :required]}
            assert cs.errors[:variants] == {"needs a variant", [validation: :required]}
            assert :items in cs.required
          end
        end)

      assert stderr == ""
    end

    test "non-empty lists pass and removing every entry fails" do
      assert {:ok, value} =
               RequiredLists.new(
                 items: [%{name: "item"}],
                 variants: [%{__type__: "child", name: "variant"}]
               )

      refute RequiredLists.change(value, items: []).valid?
      refute RequiredLists.change(value, variants: nil).valid?
    end

    test "invalid entries keep their own errors instead of a blank error" do
      assert {:error, cs} = RequiredLists.new(items: [%{}], variants: [%{__type__: "child"}])
      refute Keyword.has_key?(cs.errors, :items)
      assert [%{errors: [name: _]}] = cs.changes.items
    end
  end

  describe "struct inputs" do
    test "new/1 and change/2 apply child structs without dropping fields" do
      {:ok, child} = Child.new(name: "child")
      child = %{child | inserted_at: ~N[2000-01-01 00:00:00]}

      assert {:ok, parent} = Parent.new(child: child, kids: [child])
      assert parent.child == child
      assert parent.kids == [child]

      {:ok, other} = Child.new(name: "other")

      assert {:ok, %{kids: [^other]}} =
               parent |> Parent.change(kids: [other]) |> Parent.from_changeset()
    end

    test "a different struct honors on_replace for embeds_one" do
      {:ok, child} = Child.new(name: "child")
      {:ok, other} = Child.new(name: "other")
      {:ok, parent} = Parent.new(strict: child, replaceable: child)

      assert_raise RuntimeError, ~r/on_replace/, fn -> Parent.change(parent, strict: other) end

      assert_raise RuntimeError, ~r/on_replace/, fn ->
        Parent.changeset(parent, %{strict: other})
      end

      updated = %{child | name: "updated"}

      assert {:ok, %{strict: ^updated}} =
               parent |> Parent.change(strict: updated) |> Parent.from_changeset()

      assert {:ok, %{replaceable: ^other}} =
               parent |> Parent.change(replaceable: other) |> Parent.from_changeset()
    end
  end

  describe "polymorphic on_type_not_found" do
    test ":ignore on a single embed leaves the current value unchanged" do
      {:ok, parent} = Parent.new(poly: %{__type__: "child", name: "current"})
      cs = Parent.change(parent, poly: %{__type__: "unknown", name: "next"})
      assert cs.valid?
      assert Ecto.Changeset.apply_changes(cs).poly == parent.poly
      assert {:ok, %{poly: nil}} = Parent.new(poly: %{__type__: "unknown"})
    end

    test ":nilify is rejected for polymorphic lists" do
      assert_raise ArgumentError, ~r/does not support on_type_not_found: :nilify/, fn ->
        compile(Strukt.EmbedLifecycleTest.NilifyMany, """
        defstruct do
          polymorphic_embeds_many :items,
            types: [child: Strukt.Test.Lifecycle.Child],
            on_replace: :delete,
            on_type_not_found: :nilify
        end
        """)
      end
    end
  end

  describe "changeset actions" do
    for action <- [:validate, :replace, :ignore] do
      test "accepts and preserves the #{action} action" do
        {:ok, parent} = Parent.new()
        cs = parent |> Parent.change(count: 1) |> Map.put(:action, unquote(action))
        cs = Parent.change(cs, count: 2)
        assert cs.action == unquote(action)
        assert cs.changes.count == 2
      end
    end
  end

  test "ordinary params cannot inject generated or unknown fields" do
    for params <- [
          %{name: "ok", __strukt_autogenerated__: %{inserted_at: "invalid", injected: true}},
          %{"name" => "ok", "__strukt_autogenerated__" => %{"inserted_at" => "invalid"}}
        ] do
      cs = Child.changeset(%Child{}, params)
      assert cs.valid?
      assert cs.data.inserted_at == nil
      refute Map.has_key?(cs.data, :injected)
    end
  end

  test "direct changesets do not generate timestamps or accept submitted timestamps" do
    cs =
      Parent.changeset(%Parent{}, %{child: %{name: "child", inserted_at: ~N[2000-01-01 00:00:00]}})

    assert cs.valid?
    assert Ecto.Changeset.get_field(cs, :child).inserted_at == nil
  end

  test "all APIs trust declared child structs without rerunning required validation" do
    child = %Child{name: nil, inserted_at: ~N[2000-01-01 00:00:00]}
    assert {:ok, %{child: ^child, kids: [^child]}} = Parent.new(child: child, kids: [child])

    for cs <- [
          Parent.change(%Parent{}, child: child, kids: [child]),
          Parent.changeset(%Parent{}, %{child: child, kids: [child]})
        ] do
      assert cs.valid?
      assert Ecto.Changeset.get_field(cs, :child) == child
      assert Ecto.Changeset.get_field(cs, :kids) == [child]
    end
  end

  test "generation metadata is removed from returned params at every nesting level" do
    cs =
      Parent.change(%Parent{},
        child: %{name: "child"},
        kids: [%{name: "kid"}],
        polys: [%{__type__: :child, name: "poly"}]
      )

    assert cs.valid?
    assert {:ok, _} = Jason.encode(cs.params)
    refute Map.has_key?(cs.params["child"], {Strukt.Params, :autogenerated})
    assert {:ok, _} = Jason.encode(cs.changes.child.params)
  end

  test "nested custom timestamp generators run once and preserve existing values" do
    module = Strukt.EmbedLifecycleTest.TimedChild

    compile(module, """
    @timestamps_opts [type: :utc_datetime, inserted_at: :created_at, autogenerate: {Strukt.Test.SchemaOptions.Counter, :next, []}]
    defstruct do
      field :name, :string
      timestamps()
    end
    """)

    parent = Strukt.EmbedLifecycleTest.TimedParent

    compile(parent, """
    defstruct do
      embeds_many :items, #{inspect(module)}, on_replace: :delete
      polymorphic_embeds_many :polys, types: [child: #{inspect(module)}], on_replace: :delete
    end
    """)

    Process.put(Strukt.Test.SchemaOptions.Counter, 0)

    assert {:ok, value} =
             apply(parent, :new, [
               [items: [%{name: "one"}], polys: [%{__type__: :child, name: "two"}]]
             ])

    assert Process.get(Strukt.Test.SchemaOptions.Counter) == 2

    for child <- value.items ++ value.polys do
      assert %DateTime{} = child.created_at
      assert child.created_at == child.updated_at
    end

    cs =
      apply(parent, :change, [
        value,
        %{items: [%{name: "updated"}], polys: [%{__type__: :child, name: "updated"}]}
      ])

    assert Process.get(Strukt.Test.SchemaOptions.Counter) == 2
    assert hd(Ecto.Changeset.get_field(cs, :items)).created_at == hd(value.items).created_at
  end

  test "required lists preserve cast errors and accept an unchanged populated list" do
    assert {:ok, value} =
             RequiredLists.new(
               items: [%{name: "one"}],
               variants: [%{__type__: :child, name: "two"}]
             )

    assert RequiredLists.change(value).valid?

    for params <- [%{items: 42, variants: 42}, %{items: [nil], variants: [nil]}] do
      assert {:error, cs} = RequiredLists.new(params)
      assert [{"is invalid", _}] = Keyword.get_values(cs.errors, :items)
      assert [{"is invalid", _}] = Keyword.get_values(cs.errors, :variants)
    end
  end

  test "on_replace mark_as_invalid is respected for trusted single structs" do
    module = Strukt.EmbedLifecycleTest.InvalidReplacement

    compile(module, """
    defstruct do
      embeds_one :child, Strukt.Test.Lifecycle.Child, on_replace: :mark_as_invalid
    end
    """)

    {:ok, child} = Child.new(name: "original")
    {:ok, other} = Child.new(name: "replacement")
    {:ok, value} = apply(module, :new, [[child: child]])

    for api <- [:change, :changeset] do
      cs = apply(module, api, [value, %{child: other}])
      refute cs.valid?
      assert {"is invalid", _} = cs.errors[:child]
    end
  end

  test "pending inserts keep timestamps across partial updates and list reordering" do
    for field <- [:child, :poly, :kids, :polys] do
      many? = field in [:kids, :polys]
      first = %{name: "first", __type__: :child}
      second = %{name: "second", __type__: :child}
      value = if many?, do: [first, second], else: first
      pending = Parent.change(%Parent{}, %{field => value})
      inserted = pending |> Ecto.Changeset.get_field(field) |> List.wrap()

      params =
        Enum.reverse(inserted)
        |> Enum.map(&%{uuid: &1.uuid, name: &1.name <> " updated", __type__: :child})

      params = if many?, do: params, else: hd(params)
      updated = Parent.change(pending, %{field => params})
      assert updated.valid?

      expected = inserted |> Enum.reverse() |> Enum.map(&%{&1 | name: &1.name <> " updated"})
      assert updated |> Ecto.Changeset.get_field(field) |> List.wrap() == expected
      assert {:ok, _} = Jason.encode(updated.params)
    end
  end

  test "trusted structs can revert pending replacements and cannot bypass strict replacement" do
    {:ok, original} = Child.new(name: "original")
    {:ok, replacement} = Child.new(name: "replacement")
    {:ok, parent} = Parent.new(replaceable: original, strict: original)
    pending = Parent.change(parent, replaceable: replacement, strict: %{name: "pending"})

    reverted = Parent.change(pending, replaceable: original, strict: original)
    assert reverted.valid?
    assert Ecto.Changeset.apply_changes(reverted) == parent

    assert_raise RuntimeError, ~r/on_replace/, fn ->
      Parent.change(pending, strict: replacement)
    end
  end

  test "deeply nested children retain generated timestamps and serialize clean params" do
    module = Strukt.EmbedLifecycleTest.Root

    compile(module, """
    defstruct do
      embeds_one :parent, Strukt.Test.Lifecycle.Parent, on_replace: :update
    end
    """)

    cs =
      apply(module, :change, [
        struct(module),
        %{parent: %{child: %{name: "child"}, polys: [%{__type__: :child, name: "poly"}]}}
      ])

    assert cs.valid?
    parent = Ecto.Changeset.get_field(cs, :parent)

    for entity <- [parent, parent.child, hd(parent.polys)] do
      assert %NaiveDateTime{} = entity.inserted_at
      assert entity.inserted_at == entity.updated_at
    end

    assert {:ok, _} = Jason.encode(cs.params)
    assert {:ok, _} = Jason.encode(cs.changes.parent.params)
    updated = apply(module, :change, [cs, %{parent: %{count: 1}}])
    assert updated.valid?
    assert Ecto.Changeset.get_field(updated, :parent) == %{parent | count: 1}
  end

  test "removing generation metadata preserves opaque map values accepted by Ecto" do
    module = Strukt.EmbedLifecycleTest.OpaqueMap

    compile(module, """
    defstruct do
      field :payload, :map
    end
    """)

    payload = %{improper: [1 | :tail], nested: [%{improper: [2 | 3]}], tuple: {1, 2}}
    assert {:ok, ^payload} = Ecto.Type.cast(:map, payload)
    assert {:ok, %{payload: ^payload}} = apply(module, :new, [[payload: payload]])

    for api <- [:change, :changeset] do
      cs = apply(module, api, [struct(module), %{payload: payload}])
      assert cs.valid?
      assert Ecto.Changeset.get_field(cs, :payload) == payload
      assert cs.params["payload"] == payload
    end
  end
end
