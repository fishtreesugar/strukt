# Modified from upstream by the maintainers of the fishtreesugar/strukt fork.

defmodule Strukt.Params do
  @moduledoc """
    use Ecto.Schema's reflection to map the params.
  """

  # Ecto only casts permitted fields, so generated values such as timestamps travel
  # under this key until the nested Strukt changeset applies them to its data.
  @generated_key {__MODULE__, :autogenerated}

  defmodule Generated do
    @moduledoc false
    defstruct [:module, :values]
  end

  def transform(_module, nil = _params, nil = _struct), do: nil

  # Scalar params have no fields to map. Preserve them so Ecto can report the type mismatch
  # instead of treating them as field maps.
  def transform(_module, params, _struct)
      when not is_map(params) and not is_list(params) and not is_nil(params),
      do: params

  def transform(module, params, struct) when is_list(params) do
    case to_map(params) do
      %{} = params -> transform(module, params, struct)
      other -> other
    end
  end

  def transform(module, params, nil = _struct) when is_struct(params) do
    transform_from_struct(module, params, params)
  end

  def transform(module, params, nil = _struct) do
    struct =
      struct(module)
      |> Strukt.Autogenerate.generate()

    generated = Map.take(struct, Enum.map(Strukt.Autogenerate.get(module), &elem(&1, 0)))

    generated
    |> Map.merge(transform_from_struct(module, params, struct))
    |> mark_generated(module, generated)
  end

  def transform(module, params, struct) when is_struct(struct) do
    transform_from_struct(module, params, struct)
  end

  # Normalize record-shaped pair lists before source mapping or identity matching.
  # Preserve invalid shapes for the top-level cast or parent embed error handler.
  @doc false
  def to_map(params) when is_list(params) do
    if Enum.all?(params, fn
         {key, _value} when is_atom(key) or is_binary(key) -> true
         _ -> false
       end),
       do: Map.new(params),
       else: params
  end

  def to_map(params), do: params

  defp mark_generated(params, _module, generated) when map_size(generated) == 0, do: params

  defp mark_generated(params, module, generated) do
    Map.put(params, @generated_key, %Generated{module: module, values: generated})
  end

  # Only an internal typed value carries generation state; ordinary params cannot
  # inject data by submitting a map under a reserved-looking field name.
  @doc false
  def pop_generated(%{@generated_key => %Generated{} = generated} = params),
    do: {generated, Map.delete(params, @generated_key)}

  def pop_generated(params), do: {nil, params}

  @doc false
  def put_generated(%module{} = entity, %Generated{module: module, values: values}, cast_fields) do
    fields =
      for {field, _} <- Strukt.Autogenerate.get(module), field not in cast_fields, do: field

    Enum.reduce(fields, entity, fn field, entity ->
      if is_nil(Map.get(entity, field)),
        do: Map.replace!(entity, field, Map.fetch!(values, field)),
        else: entity
    end)
  end

  def put_generated(entity, _generated, _cast_fields), do: entity

  @doc false
  def drop_generated_params(%Ecto.Changeset{params: params} = changeset) do
    %{changeset | params: drop_generated(params)}
  end

  defp drop_generated(%_{} = value), do: value

  defp drop_generated(params) when is_map(params) do
    {_generated, params} = pop_generated(params)
    Map.new(params, fn {key, value} -> {key, drop_generated(value)} end)
  end

  # Map/custom-field params may contain improper lists; preserve their tails too.
  defp drop_generated([head | tail]), do: [drop_generated(head) | drop_generated(tail)]
  defp drop_generated(value), do: value

  # Preserve explicit nil, including invalid nil elements inside embed lists.
  defp transform(_module, nil, _struct, cardinality: :one), do: nil

  # Structs are trusted, already-cast values. Casting applies them directly, or reports
  # an error for a struct of another schema.
  defp transform(_module, %_{} = params, _struct, cardinality: :one), do: params

  defp transform(module, params, struct, cardinality: :one) do
    formed = transform(module, params, struct)

    # Keep the existing embed identity without submitting its other fields for recasting.
    if is_map(formed) and is_struct(struct) do
      Map.merge(Map.take(struct, module.__schema__(:primary_key)), formed)
    else
      formed
    end
  end

  defp transform(module, params, struct, cardinality: :many) when is_list(params) do
    current = embed_index(struct)

    params
    |> Enum.with_index()
    |> Enum.map(fn
      {%_{} = param, _index} ->
        param

      {param, index} ->
        selected = current_embed(module, param, current, index, :source)
        transform(module, param, selected, cardinality: :one)
    end)
  end

  defp transform(module, params, struct, cardinality: :many)
       when is_map(params) and not is_struct(params) do
    transform(module, indexed_values(params), struct, cardinality: :many)
  end

  # Delay invalid shapes until casting can return a field error.
  defp transform(_module, params, _struct, cardinality: :many), do: params

  defp transform_from_struct(module, params, struct) do
    Enum.reduce(Map.from_struct(struct), %{}, fn {field, _current}, acc ->
      value = fetch_field_param(module, params, field, :source)

      case value do
        {:ok, value} ->
          {field, value} = map_value_to_field(module, field, value, struct, params)
          Map.put(acc, field, value)

        :error ->
          acc
      end
    end)
  end

  defp map_value_to_field(module, field, value, struct, params) do
    case module.__schema__(:type, field) do
      # since ecto 3.12.0, parameterized type represent as a tuple instead of a triple
      # see https://github.com/elixir-ecto/ecto/commit/21c6068
      {:parameterized,
       {Ecto.Embedded,
        %Ecto.Embedded{
          cardinality: cardinality,
          related: embedded_module
        }}} ->
        {field,
         transform(embedded_module, value, get_struct_field_value(struct, field),
           cardinality: cardinality
         )}

      {:parameterized, {PolymorphicEmbed, opts}} ->
        context =
          if parent_field = opts.use_parent_field_for_type do
            type =
              case fetch_field_param(module, params, parent_field, :source) do
                {:ok, value} ->
                  struct
                  |> Ecto.Changeset.cast(%{parent_field => value}, [parent_field])
                  |> Ecto.Changeset.get_field(parent_field)

                :error ->
                  Map.get(struct, parent_field)
              end

            [parent_type: type]
          else
            []
          end

        {field,
         transform_polymorphic(
           module,
           field,
           value,
           get_struct_field_value(struct, field),
           context
         )}

      {:array, {:parameterized, {PolymorphicEmbed, _opts}}} ->
        {field,
         transform_polymorphic(module, field, value, get_struct_field_value(struct, field),
           cardinality: :many
         )}

      _type ->
        {field, value}
    end
  end

  defp transform_polymorphic(module, field, params, struct, opts \\ [])

  # Keep nil as-is so clearing and required validation can run later.
  defp transform_polymorphic(_module, _field, nil, _struct, _opts), do: nil

  # Struct params have already been cast by the caller, so leave them untouched.
  defp transform_polymorphic(_module, _field, %_{} = params, _struct, _opts), do: params

  defp transform_polymorphic(module, field, params, struct, cardinality: :many)
       when is_map(params) do
    transform_polymorphic(module, field, indexed_values(params), struct, cardinality: :many)
  end

  # Select each map's current data by primary key, or by position when no key is supplied.
  # Already-cast structs in the list are preserved.
  defp transform_polymorphic(module, field, params, struct, cardinality: :many)
       when is_list(params) do
    current = embed_index(struct)

    params
    |> Enum.with_index()
    |> Enum.map(fn
      {%_{} = param, _index} ->
        param

      {param, index} ->
        selected =
          if is_map(param) do
            case infer_polymorphic(polymorphic_options(module, field), param) do
              {:ok, embedded_module} ->
                current_embed(embedded_module, param, current, index, :source)

              _ ->
                nil
            end
          end

        transform_polymorphic(module, field, param, selected)
    end)
  end

  # Normalize maps using their inferred variant, or the current single embed for partial updates.
  # Without either context, leave type-not-found handling to the casting policy.
  defp transform_polymorphic(module, field, params, struct, opts) when is_map(params) do
    field_opts = polymorphic_options(module, field)
    struct = embedded_data(struct)

    selected =
      case Keyword.fetch(opts, :parent_type) do
        {:ok, type} -> variant_module(field_opts, type)
        :error -> resolve_polymorphic(field_opts, params, struct)
      end

    case selected do
      {:ok, embedded_module} ->
        type_field_name = field_opts.type_field_name

        type =
          case fetch_param(params, type_field_name) do
            {:ok, type} -> type
            :error -> PolymorphicEmbed.get_polymorphic_type(module, field, embedded_module)
          end

        struct = polymorphic_struct_for_module(struct, embedded_module)

        embedded_module
        |> transform(params, struct)
        |> maybe_put_polymorphic_type(type_field_name, type)

      _ ->
        params
    end
  end

  # Leave invalid shapes alone so the eventual cast can report the type error.
  defp transform_polymorphic(_module, _field, params, _struct, _opts), do: params

  defp polymorphic_struct_for_module(struct, module) when is_struct(struct, module), do: struct
  defp polymorphic_struct_for_module(_struct, _module), do: nil

  defp polymorphic_options(module, field) do
    case module.__schema__(:type, field) do
      {:parameterized, {PolymorphicEmbed, opts}} -> opts
      {:array, {:parameterized, {PolymorphicEmbed, opts}}} -> opts
    end
  end

  defp variant_module(opts, type) when is_atom(type) or is_binary(type) do
    case Enum.find(opts.types_metadata, &(to_string(&1.type) == to_string(type))) do
      %{module: module} -> {:ok, module}
      nil -> :error
    end
  end

  defp variant_module(_opts, _type), do: :error

  defp infer_polymorphic(opts, params) do
    case fetch_param(params, opts.type_field_name) do
      {:ok, nil} ->
        :error

      {:ok, type} ->
        variant_module(opts, type)

      :error ->
        keys = for key <- Map.keys(params), is_atom(key) or is_binary(key), do: to_string(key)

        case Enum.find(opts.types_metadata, fn meta ->
               meta.identify_by_fields != [] and
                 Enum.all?(meta.identify_by_fields, &(to_string(&1) in keys))
             end) do
          %{module: module} -> {:ok, module}
          nil -> :missing
        end
    end
  end

  defp resolve_polymorphic(opts, params, current) do
    case infer_polymorphic(opts, params) do
      :missing ->
        if is_struct(current) and valid_embed_input?(current, opts),
          do: {:ok, current.__struct__},
          else: :error

      result ->
        result
    end
  end

  # Restore the type marker after source mapping so casting can select the variant.
  defp maybe_put_polymorphic_type(params, _type_field_name, nil), do: params

  defp maybe_put_polymorphic_type(params, type_field_name, type),
    do: Map.put(params, type_field_name, type)

  @doc false
  def cast_embed(changeset, field) do
    {:embed, relation} = changeset.types[field]
    values = Map.get(changeset.params, to_string(field))

    values =
      case {relation.cardinality, values} do
        {:one, values} ->
          to_map(values)

        {:many, values} when is_map(values) and not is_struct(values) ->
          values |> indexed_values() |> Enum.map(&to_map/1)

        {:many, values} when is_list(values) ->
          Enum.map(values, &to_map/1)

        {:many, values} ->
          values
      end

    if relation.cardinality == :many and is_list(values) and Enum.any?(values, &is_list/1) do
      Ecto.Changeset.add_error(changeset, field, "is invalid",
        validation: :embed,
        type: {:array, :map}
      )
    else
      %{changeset | params: Map.put(changeset.params, to_string(field), values)}
      |> do_cast_embed(field, relation, values)
      |> Map.put(:params, changeset.params)
    end
  end

  defp do_cast_embed(changeset, field, relation, values) do
    struct_inputs? =
      relation.cardinality == :many and is_list(values) and Enum.any?(values, &is_struct/1)

    current = Ecto.Changeset.get_field(changeset, field)
    original = Map.fetch!(changeset.data, field)
    pending? = Map.has_key?(changeset.changes, field)
    no_keys? = relation.related.__schema__(:primary_key) == []

    with_callback =
      case relation.cardinality do
        :one ->
          fn fresh, params ->
            action = embed_action(relation, fresh, original)

            if pending?,
              do:
                cast_pending_embed(fresh, params, current, action, relation.on_replace == :update),
              else: cast_child(fresh, params, action)
          end

        :many ->
          # Build lookups once so each entry is matched in constant time.
          current = embed_index(current)
          inputs = if is_list(values), do: List.to_tuple(values), else: {}
          originals = if no_keys?, do: MapSet.new(), else: MapSet.new(List.wrap(original))

          fn fresh, params, index ->
            action = if MapSet.member?(originals, fresh), do: :update, else: :insert

            case index < tuple_size(inputs) and elem(inputs, index) do
              %_{} = entity ->
                data = current_embed(fresh.__struct__, entity, current, index) || fresh
                Ecto.Changeset.change(data, Map.from_struct(entity))

              _ when pending? or no_keys? ->
                selected = current_embed(fresh.__struct__, params, current, index)
                cast_pending_embed(fresh, params, selected, action)

              _ ->
                cast_child(fresh, params, action)
            end
          end
      end

    if struct_inputs? do
      if Enum.all?(values, &(not is_struct(&1) or is_struct(&1, relation.related))) do
        params =
          Enum.map(values, fn
            %_{} = entity -> Map.from_struct(entity)
            params -> params
          end)

        %{changeset | params: Map.put(changeset.params, to_string(field), params)}
        |> Ecto.Changeset.cast_embed(field, with: with_callback)
        |> Map.put(:params, changeset.params)
      else
        Ecto.Changeset.add_error(changeset, field, "is invalid",
          validation: :embed,
          type: {:array, :map}
        )
      end
    else
      Ecto.Changeset.cast_embed(changeset, field, with: with_callback)
    end
  end

  defp embed_action(%{cardinality: :one, on_replace: :update}, _fresh, original)
       when not is_nil(original),
       do: :update

  defp embed_action(relation, fresh, original) do
    if relation.related.__schema__(:primary_key) != [] and fresh === original,
      do: :update,
      else: :insert
  end

  defp cast_child(%module{} = data, params, action) do
    if Strukt in List.flatten(Keyword.get_values(module.__info__(:attributes), :behaviour)) do
      module.changeset(data, params, action)
    else
      # Ecto schemas that are not Strukt schemas retain the conventional callback.
      {_generated, params} = pop_generated(params)
      data |> module.changeset(params) |> Map.put(:action, action)
    end
  end

  @doc false
  def put_embed_struct(changeset, field, entity) do
    {:embed, relation} = changeset.types[field]

    if relation.cardinality == :one and is_struct(entity, relation.related) do
      current = Ecto.Changeset.get_field(changeset, field)
      original = Map.fetch!(changeset.data, field)

      # Keep the matching identity as the base so Ecto applies `on_replace` to
      # replacements, as it does for maps.
      data =
        cond do
          same_identity?(original, entity) -> original
          same_identity?(current, entity) -> current
          current != nil and relation.on_replace == :update -> current
          true -> struct(relation.related)
        end

      Ecto.Changeset.put_embed(
        changeset,
        field,
        Ecto.Changeset.change(data, Map.from_struct(entity))
      )
    else
      type = if relation.cardinality == :one, do: :map, else: {:array, :map}
      Ecto.Changeset.add_error(changeset, field, "is invalid", validation: :embed, type: type)
    end
  end

  defp same_identity?(%module{} = current, %module{} = entity) do
    case Ecto.primary_key(current) do
      [] ->
        false

      keys ->
        Enum.all?(keys, fn {key, value} -> value != nil and Map.get(entity, key) == value end)
    end
  end

  defp same_identity?(_current, _entity), do: false

  @doc false
  def supplied_fields(params, fields) do
    Enum.filter(fields, &(fetch_param(params, &1) != :error))
  end

  defp cast_pending_embed(%module{}, params, current, action, update? \\ false) do
    same_identity? =
      is_struct(current, module) and
        (update? or
           Enum.all?(Ecto.primary_key(current), fn {key, value} ->
             case fetch_param(params, key) do
               {:ok, param} ->
                 Ecto.Type.cast(module.__schema__(:type, key), param) == {:ok, value}

               :error ->
                 is_nil(value)
             end
           end))

    cast_child(if(same_identity?, do: current, else: struct(module)), params, action)
  end

  @doc false
  def clear_embed(changeset, field) do
    {:embed, %{cardinality: cardinality}} = changeset.types[field]
    empty = if cardinality == :many, do: [], else: nil
    Ecto.Changeset.put_embed(changeset, field, empty)
  end

  @doc false
  def cast_polymorphic_embed(field, changeset) do
    case Map.fetch(changeset.params || %{}, to_string(field)) do
      :error -> changeset
      {:ok, value} -> cast_polymorphic_value(changeset, field, value)
    end
  end

  defp cast_polymorphic_value(changeset, field, value) do
    case {changeset.types[field], value} do
      {{:array, _}, values} when is_map(values) and not is_struct(values) ->
        cast_polymorphic_value(changeset, field, indexed_values(values))

      {{:array, _}, nil} ->
        Ecto.Changeset.put_change(changeset, field, [])

      {_, nil} ->
        Ecto.Changeset.put_change(changeset, field, nil)

      {{:array, {:parameterized, {PolymorphicEmbed, opts}}}, values} when is_list(values) ->
        if Enum.all?(values, &valid_embed_input?(&1, opts)) do
          cast_polymorphic_many(changeset, field, values, opts)
        else
          Ecto.Changeset.add_error(changeset, field, "is invalid")
        end

      {{:parameterized, {PolymorphicEmbed, opts}}, %_{} = entity} ->
        if valid_embed_input?(entity, opts) do
          Ecto.Changeset.put_change(changeset, field, entity)
        else
          Ecto.Changeset.add_error(changeset, field, "is invalid")
        end

      {{:parameterized, {PolymorphicEmbed, opts}}, params}
      when is_map(params) and not is_struct(params) ->
        cast_polymorphic_one(changeset, field, params, opts)

      _ ->
        Ecto.Changeset.add_error(changeset, field, "is invalid")
    end
  end

  defp valid_embed_input?(%module{}, opts),
    do: Enum.any?(opts.types_metadata, &(&1.module == module))

  defp valid_embed_input?(value, _opts), do: is_map(value)

  defp cast_polymorphic_one(changeset, field, params, opts) do
    current = changeset |> Ecto.Changeset.get_field(field) |> embedded_data()

    selected =
      if parent_field = opts.use_parent_field_for_type do
        parent_type = Ecto.Changeset.get_field(changeset, parent_field)

        case {variant_module(opts, parent_type), fetch_param(params, opts.type_field_name)} do
          {{:ok, module}, :error} ->
            {:ok, module}

          {{:ok, module}, {:ok, type}} when is_atom(type) or is_binary(type) ->
            if to_string(parent_type) == to_string(type),
              do: {:ok, module},
              else:
                raise(
                  "type specified in the parent field #{inspect(parent_type)} does not match the type in the embedded map #{inspect(type)}"
                )

          _ ->
            :error
        end
      else
        resolve_polymorphic(opts, params, current)
      end

    case selected do
      {:ok, module} ->
        data = polymorphic_struct_for_module(current, module)
        cs = cast_child(data || struct(module), params, if(data, do: :update, else: :insert))
        put_polymorphic(changeset, field, polymorphic_value(cs), cs.valid?)

      _ ->
        unknown_polymorphic(changeset, field, params, opts.on_type_not_found)
    end
  end

  defp cast_polymorphic_many(changeset, field, values, opts) do
    current = embed_index(Ecto.Changeset.get_field(changeset, field))

    result =
      values
      |> Enum.with_index()
      |> Enum.reduce_while({[], true}, fn
        {%_{} = entity, _index}, {acc, valid?} ->
          {:cont, {[entity | acc], valid?}}

        {params, index}, {acc, valid?} ->
          case infer_polymorphic(opts, params) do
            {:ok, module} ->
              data = current_embed(module, params, current, index)

              cs =
                cast_child(data || struct(module), params, if(data, do: :update, else: :insert))

              {:cont, {[polymorphic_value(cs) | acc], valid? and cs.valid?}}

            _ when opts.on_type_not_found == :ignore ->
              {:cont, {acc, valid?}}

            _ ->
              {:halt,
               {:error, unknown_polymorphic(changeset, field, params, opts.on_type_not_found)}}
          end
      end)

    case result do
      {:error, changeset} -> changeset
      {reversed, valid?} -> put_polymorphic(changeset, field, Enum.reverse(reversed), valid?)
    end
  end

  defp polymorphic_value(%Ecto.Changeset{valid?: true} = cs), do: Ecto.Changeset.apply_changes(cs)
  defp polymorphic_value(cs), do: cs

  defp put_polymorphic(changeset, field, value, valid?) do
    changeset
    |> Ecto.Changeset.put_change(field, value)
    |> Map.put(:valid?, changeset.valid? and valid?)
  end

  defp unknown_polymorphic(changeset, field, _params, :nilify),
    do: Ecto.Changeset.put_change(changeset, field, nil)

  defp unknown_polymorphic(changeset, _field, _params, :ignore), do: changeset

  defp unknown_polymorphic(_changeset, _field, params, :raise),
    do: raise("could not infer polymorphic embed from data #{inspect(params)}")

  defp unknown_polymorphic(changeset, field, _params, :changeset_error),
    do: Ecto.Changeset.add_error(changeset, field, "is invalid")

  # Index current entries by position and by `{module, primary key}`. The first entry
  # with a given identity wins, matching a linear search.
  defp embed_index(current) do
    entries = current |> List.wrap() |> Enum.map(&embedded_data/1)

    identities =
      Enum.reduce(entries, %{}, fn
        %module{} = entry, acc ->
          case schema_primary_key(module) do
            [] -> acc
            keys -> Map.put_new(acc, {module, Enum.map(keys, &Map.get(entry, &1))}, entry)
          end

        _entry, acc ->
          acc
      end)

    {List.to_tuple(entries), identities}
  end

  defp schema_primary_key(module) do
    if function_exported?(module, :__schema__, 1), do: module.__schema__(:primary_key), else: []
  end

  # Explicit keys must never fall back to another entry's position, even if the key
  # is nil, invalid, incomplete, or does not match any current entry.
  defp current_embed(module, params, {entries, identities}, index, key_mode \\ :field) do
    params = to_map(params)
    keys = module.__schema__(:primary_key)
    supplied = Enum.map(keys, &{&1, fetch_field_param(module, params, &1, key_mode)})

    if Enum.any?(supplied, fn {_key, result} -> result != :error end) do
      supplied
      |> Enum.reduce_while([], fn
        {key, {:ok, value}}, acc ->
          case Ecto.Type.cast(module.__schema__(:type, key), value) do
            {:ok, value} when not is_nil(value) -> {:cont, [value | acc]}
            _ -> {:halt, :error}
          end

        {_key, :error}, _acc ->
          {:halt, :error}
      end)
      |> case do
        :error -> nil
        values -> Map.get(identities, {module, Enum.reverse(values)})
      end
    else
      if index < tuple_size(entries),
        do: polymorphic_struct_for_module(elem(entries, index), module)
    end
  end

  defp fetch_field_param(_module, %_{} = params, field, :source),
    do: fetch_param(params, field)

  defp fetch_field_param(module, params, field, :source) do
    source = module.__schema__(:field_source, field) || field

    case fetch_param(params, source) do
      :error -> fetch_param(params, field)
      found -> found
    end
  end

  defp fetch_field_param(_module, params, field, :field), do: fetch_param(params, field)

  defp embedded_data(%Ecto.Changeset{} = changeset), do: Ecto.Changeset.apply_changes(changeset)
  defp embedded_data(value), do: value

  # Match Ecto's indexed-map ordering, including numeric strings such as "2" and "10".
  defp indexed_values(params) do
    params
    |> Enum.map(fn
      {key, value} when is_binary(key) and byte_size(key) < 32 ->
        case Integer.parse(key) do
          {index, ""} -> {index, value}
          _ -> {key, value}
        end

      entry ->
        entry
    end)
    |> Enum.sort()
    |> Enum.map(&elem(&1, 1))
  end

  defp fetch_param(params, _field) when not is_map(params), do: :error

  defp fetch_param(params, field) do
    with :error <- Map.fetch(params, field), do: Map.fetch(params, to_string(field))
  end

  defp get_struct_field_value(struct, field) do
    case struct do
      nil -> nil
      struct -> Map.get(struct, field)
    end
  end
end
